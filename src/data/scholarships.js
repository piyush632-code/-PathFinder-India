export function matchScholarships(profile) {
  const { gradeLevel, category, gender, percentage, stream, annualIncome, isSingleGirlChild, isMinority, minorityCommunity } = profile;

  return SCHOLARSHIPS.filter(s => {
    const elig = s.eligibility;

    // Grade check
    if (elig.grades && !elig.grades.some(g => g === gradeLevel || g === "graduation")) {
      if (!elig.grades.includes(gradeLevel)) return false;
    }

    // Percentage check
    if (percentage && elig.minPercentage > 0 && percentage < elig.minPercentage) return false;

    // Income check
    if (elig.incomeLimit && annualIncome && annualIncome > elig.incomeLimit) return false;

    // Category check
    if (elig.categories && category && !elig.categories.includes(category)) return false;

    // Gender check
    if (elig.genderSpecific && gender !== elig.genderSpecific) return false;

    // Single girl child
    if (elig.singleGirlChild && !isSingleGirlChild) return false;

    // Minority
    if (elig.minority && !isMinority) return false;

    // Stream check for science-specific
    if (elig.streams && stream && !elig.streams.includes(stream)) return false;

    return true;
  }).sort((a, b) => b.amountValue - a.amountValue);
}

